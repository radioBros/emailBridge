// Command errgen generates internal/errs/codes_gen.go and docs/api/problems.md
// from internal/errs/codes.yaml.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"go.yaml.in/yaml/v3"
)

type fileDoc struct {
	Codes []codeEntry `yaml:"codes"`
}

type codeEntry struct {
	Code   string `yaml:"code"`
	Kind   string `yaml:"kind"`
	Status *int   `yaml:"status"`
	Phase  string `yaml:"phase"`
	Title  string `yaml:"title"`
}

func main() {
	check := flag.Bool("check", false, "exit non-zero if generated files are stale")
	flag.Parse()

	root, err := findRoot()
	if err != nil {
		fail(err)
	}
	yamlPath := filepath.Join(root, "internal", "errs", "codes.yaml")
	raw, err := os.ReadFile(yamlPath) //nolint:gosec // G304: path is fixed under module root.
	if err != nil {
		fail(err)
	}
	var doc fileDoc
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		fail(fmt.Errorf("parse codes.yaml: %w", err))
	}
	if len(doc.Codes) == 0 {
		fail(fmt.Errorf("codes.yaml: no codes"))
	}

	goOut := filepath.Join(root, "internal", "errs", "codes_gen.go")
	mdOut := filepath.Join(root, "docs", "api", "problems.md")
	goSrc, err := format.Source(genGo(doc.Codes))
	if err != nil {
		fail(fmt.Errorf("gofmt generated code: %w", err))
	}
	mdSrc := genMD(doc.Codes)

	if *check {
		ok := true
		if !bytesEqualFile(goOut, goSrc) {
			fmt.Fprintf(os.Stderr, "stale: %s\n", goOut)
			ok = false
		}
		if !bytesEqualFile(mdOut, mdSrc) {
			fmt.Fprintf(os.Stderr, "stale: %s\n", mdOut)
			ok = false
		}
		if !ok {
			os.Exit(1)
		}
		return
	}

	if err := os.WriteFile(goOut, goSrc, 0o600); err != nil {
		fail(err)
	}
	if err := os.MkdirAll(filepath.Dir(mdOut), 0o750); err != nil {
		fail(err)
	}
	if err := os.WriteFile(mdOut, mdSrc, 0o600); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "errgen: %v\n", err)
	os.Exit(1)
}

func findRoot() (string, error) {
	wd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	dir := wd
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found from %s", wd)
		}
		dir = parent
	}
}

func bytesEqualFile(path string, want []byte) bool {
	got, err := os.ReadFile(path) //nolint:gosec // G304: path under module root.
	if err != nil {
		return false
	}
	return bytes.Equal(got, want)
}

func genGo(codes []codeEntry) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/errgen. DO NOT EDIT.\n\n")
	b.WriteString("package errs\n\n")
	b.WriteString("// Code is a stable problem-code identifier (RFC 9457 `code` field).\n")
	b.WriteString("type Code string\n\n")
	b.WriteString("const (\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\t// Code%s is %q.\n", exportName(c.Code), c.Code)
		fmt.Fprintf(&b, "\tCode%s Code = %q\n", exportName(c.Code), c.Code)
	}
	b.WriteString(")\n\n")
	b.WriteString("type codeInfo struct {\n")
	b.WriteString("\tKind   Kind\n")
	b.WriteString("\tStatus int // 0 = attempt-only (not returned as HTTP)\n")
	b.WriteString("\tTitle  string\n")
	b.WriteString("\tPhase  string\n")
	b.WriteString("}\n\n")
	b.WriteString("var catalog = map[Code]codeInfo{\n")
	for _, c := range codes {
		status := 0
		if c.Status != nil {
			status = *c.Status
		}
		fmt.Fprintf(&b, "\tCode%s: {Kind: Kind(%q), Status: %d, Title: %q, Phase: %q},\n",
			exportName(c.Code), c.Kind, status, c.Title, c.Phase)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func genMD(codes []codeEntry) []byte {
	var b bytes.Buffer
	b.WriteString("# Problem codes\n\n")
	b.WriteString("EmailBridge API errors use [RFC 9457](https://www.rfc-editor.org/rfc/rfc9457) ")
	b.WriteString("`application/problem+json` responses. The `type` URI for each code is ")
	b.WriteString("`https://emailbridge.dev/problems/<code>`.\n\n")
	b.WriteString("Codes are stable forever once released: they are never renamed, removed, or reused. ")
	b.WriteString("This file is generated from `internal/errs/codes.yaml` by `go run ./tools/errgen`.\n\n")
	b.WriteString("| Code | Kind | HTTP status | Title |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	for _, c := range codes {
		status := "—"
		if c.Status != nil {
			status = fmt.Sprintf("%d", *c.Status)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n",
			c.Code, c.Kind, status, c.Title)
	}
	return b.Bytes()
}

// initialisms are written in upper case, as Go style requires (CodeAPIKeyInvalid, CodeSMTPTemporary).
var initialisms = map[string]string{"api": "API", "id": "ID", "ip": "IP", "mfa": "MFA", "smtp": "SMTP", "tls": "TLS",
	"url": "URL", "http": "HTTP", "csrf": "CSRF", "imap": "IMAP", "pec": "PEC", "oidc": "OIDC", "otp": "OTP", "dsn": "DSN"}

func exportName(code string) string {
	parts := strings.Split(code, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		if up, ok := initialisms[p]; ok {
			b.WriteString(up)
			continue
		}
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}
